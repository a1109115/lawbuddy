def _outline(stable_id: str, title: str) -> list[str]:
    if stable_id == "CIV14":
        return ["证据目录", "证明目的与来源说明"]
    if title.startswith(("代理词", "辩护", "法律意见")):
        return ["委托与审查范围", "事实及证据", "争议焦点与分析", "结论与待核实事项"]
    if title == "律师函":
        return ["委托与收函主体", "事实与证据", "履行要求与期限", "注意事项与落款"]
    if title == "报案材料":
        return ["报案人信息", "涉嫌行为与事实", "损失与证据线索", "请求与落款"]
    if title == "担保书":
        return ["担保主体", "担保对象与财产", "担保范围", "确认与签署"]
    if "答辩" in title:
        return ["当事人信息", "答辩意见", "事实与理由", "证据与落款"]
    return ["当事人及程序信息", "请求事项", "事实与理由", "证据与落款"]


def catalog() -> list[dict[str, Any]]:
    result = []
    for stable_id, title, line, field_text, check in CATALOG:
        fields = list(dict.fromkeys(["我方角色", "当事人信息", "提交对象", *field_text.split("|")]))
        headings = _outline(stable_id, title)
        body = f"# {title}\n\n" + "\n".join(f"{name}：{{{{{name}}}}}" for name in fields)
        body += "\n\n" + "\n\n".join(f"## {heading}\n{{{{{heading}内容}}}}" for heading in headings)
        all_fields = [*fields, *(f"{heading}内容" for heading in headings)]
        result.append({
            "stableId": stable_id, "title": title, "docType": title, "category": stable_id[:3],
            "fields": [{"name": name, "label": name, "required": False, "sourcePolicy": "confirm_or_evidence"} for name in all_fields],
            "outline": headings, "writingChecks": [check, "未填写信息以 xx 标注，不强制补填", "事实来源区分原文、用户确认和待核实",
                                                      "法律效力与适用条件须核验，不沿用样例案情"],
            "contentMd": body,
            "sourceMap": {"sourceName": SOURCE_NAME, "sha256": SOURCE_HASH, "chapterStartLine": line},
            "reviewStatus": "needs_human", "version": 1,
        })
    return result


def install(case_id: str) -> list[dict[str, Any]]:
    with _INSTALL_LOCK:
        return _install(case_id)


def _install(case_id: str) -> list[dict[str, Any]]:
    require_case_mode(case_id, "document_generation")
    for config in catalog():
        prior = get_db().query_one(
            "SELECT template_id FROM best_practice_templates WHERE case_id = ? AND stable_id = ?",
            (case_id, config["stableId"]),
        )
        if prior:
            continue
        template = docgen.import_template(config["contentMd"], config["title"], config["docType"],
                                          case_id=case_id, source_name=SOURCE_NAME, template_mode="reference")
        with get_db().transaction() as conn:
            conn.execute("INSERT INTO best_practice_templates VALUES (?, ?, ?, ?)",
                         (template["id"], config["stableId"], case_id, json.dumps(config, ensure_ascii=False)))
    return list_templates(case_id)


def list_templates(case_id: str) -> list[dict[str, Any]]:
    rows = get_db().query("SELECT * FROM best_practice_templates WHERE case_id = ? ORDER BY stable_id", (case_id,))
    return [{**json.loads(row["config_json"]), "templateId": row["template_id"]} for row in rows]
