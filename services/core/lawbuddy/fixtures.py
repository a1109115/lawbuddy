def seed_demo_case(workspace_id: str) -> str:
    """创建演示案件并导入虚构文档，返回案件 ID。"""
    case = create_case(
        title=DEMO_TITLE,
        case_type="civil",
        client_name="张三",
        client_role="原告",
        stage="一审",
        default_mode="legal_review",
        permission_preset="strict_local",
        workspace_id=workspace_id,
    )

    with tempfile.TemporaryDirectory(prefix="lawbuddy-seed-") as tmp:
        tmp_path = Path(tmp)
        paths: list[str] = []

        for name, text in _TXT_DOCS.items():
            p = tmp_path / name
            p.write_text(text, encoding="utf-8")
            paths.append(str(p))

        for name, blocks in _DOCX_DOCS.items():
            p = tmp_path / name
            _write_docx(p, blocks)
            paths.append(str(p))

        import_documents(case["id"], paths)

    return case["id"]


def _write_docx(path: Path, blocks: list[tuple[int, str]]) -> None:
    from docx import Document

    doc = Document()
    for level, text in blocks:
        if level == 0:
            para = doc.add_paragraph(text)
            para.paragraph_format.first_line_indent = None
        else:
            doc.add_heading(text, level=level)
    doc.save(str(path))
